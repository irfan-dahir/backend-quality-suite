"""One source -> generated per-harness files in a consumer project.

The source is this module plus the suite's own `commands/*.md`. Every target is a
pure function `(current text or None) -> new text or None`, so preview, apply and
--check are the same computation: preview prints the planned changes, apply writes
exactly those, --check reports whether any change is planned. Re-running after an
apply plans nothing — idempotency is a property of the shape, not a test hope.

Paths and formats come from docs/research/harness-support-matrix-2026-10-08.md.
Anything that doc marks UNVERIFIED, or whose entry shape it does not give, is
printed as an instruction rather than written. User-level-only harnesses (Devin
Desktop, Cline) are instructions only: this never writes outside the project.

Ownership is narrow and explicit, so user content is never clobbered:
  * Markdown/TOML: a marked block; text outside it is preserved byte-for-byte.
  * JSON: exactly one key we own (e.g. mcpServers["design-suite"]); the rest of
    the object round-trips. A file that will not parse as JSON (JSONC comments)
    is a refusal for that file — reported, never rewritten.
"""
from __future__ import annotations

import json
import shutil
import re
from dataclasses import dataclass, field
from pathlib import Path

SERVER = "design-suite"
BEGIN_MD = "<!-- BEGIN design-suite (generated by `design-suite harness`; edits inside are overwritten) -->"
END_MD = "<!-- END design-suite -->"
BEGIN_TOML = "# BEGIN design-suite (generated by `design-suite harness`; edits inside are overwritten)"
END_TOML = "# END design-suite"
SKILL_DIRS = (".agents/skills", ".devin/skills")
CLAUDE_SKILL_DIR = ".claude/skills"
SKILL_MARK = "<!-- generated by `design-suite harness` from commands/{name}.md; do not edit -->"
CODEX_AGENTS_CAP = 32 * 1024
LOCATOR = "${DESIGN_SUITE_HOME}"


class Unparseable(Exception):
    pass


@dataclass
class Plan:  # noqa
    writes: dict = field(default_factory=dict)      # rel path -> new text
    unchanged: list = field(default_factory=list)
    refusals: list = field(default_factory=list)    # (rel, reason): could not determine
    instructions: list = field(default_factory=list)
    warnings: list = field(default_factory=list)
    warnings_pre: list = field(default_factory=list)


# --------------------------------------------------------------------- AGENTS.md
def agents_block(suite_root: Path) -> str:
    return f"""{BEGIN_MD}
## Design suite

This project uses the **design suite**: read-only design-system audits, doc-role
resolution, and guided playbooks. It is reachable from any harness three ways:
the MCP server `{SERVER}` (tools only), the `design-suite` CLI, or the scripts
directly.

**If `.design-suite/` is missing**, the project has not been onboarded. Call the
MCP tool `project_status` (or run `design-suite survey`) and **offer** onboarding
to the user. Never start onboarding yourself — it writes project files.

**Exit-code contract — never read silence as clean.**
`0` checked and clean · `1` checked, findings · `2` **could not check** (refused,
INERT, disabled, missing config) — this is never a pass and must be reported as
"not checked" · `4` doc role declined · `5` doc role is an unwritten stub.

**Running audits**

```bash
design-suite list                       # every subcommand
design-suite audit tokens               # any audit: design-suite audit <name>
design-suite doctor                     # profile + harness wiring
python3 "$DESIGN_SUITE_HOME/bin/audit_tokens.py"   # without the CLI
```

`DESIGN_SUITE_HOME` is the suite root; `design-suite where` prints it. Skills in
`.agents/skills/` refer to scripts through it.

**Invocation tiers.** Skills marked *explicit-tier* generate content or set
project conventions. Run them **only on a direct user request** — never on your
own initiative, even when they look relevant. Auto-tier skills are read-only and
may be run when useful.
{END_MD}
"""


def upsert_block(current: "str | None", block: str, begin: str, end: str) -> str:
    if current is None:
        return block
    i, j = current.find(begin), current.find(end)
    if i != -1 and j != -1 and j > i:
        tail = current[j + len(end):]
        if tail.startswith("\n"):
            tail = tail[1:]
        return current[:i] + block + tail
    if i != -1 or j != -1:
        raise Unparseable(f"only one of the design-suite markers is present — "
                          f"refusing to guess where the block ends")
    sep = "" if current.endswith("\n\n") else ("\n" if current.endswith("\n") else "\n\n")
    return current + sep + block


# ------------------------------------------------------------------------- JSON
def _load_json(current: "str | None") -> dict:
    if current is None or not current.strip():
        return {}
    try:
        data = json.loads(current)
    except json.JSONDecodeError as e:
        raise Unparseable(f"not strict JSON ({e.msg}, line {e.lineno}); comments/"
                          f"trailing commas are not round-trippable — add the entry by hand")
    if not isinstance(data, dict):
        raise Unparseable("top level is not an object")
    return data


def _dump(data: dict) -> str:
    return json.dumps(data, indent=2) + "\n"


def json_set(current, path: "tuple[str, ...]", value) -> str:
    data = _load_json(current)
    node = data
    for k in path[:-1]:
        nxt = node.setdefault(k, {})
        if not isinstance(nxt, dict):
            raise Unparseable(f"{'.'.join(path[:-1])} exists and is not an object")
        node = nxt
    node[path[-1]] = value
    out = _dump(data)
    # Already-equal content written by someone else in another style: leave it.
    if current is not None and _load_json(current) == data:
        return current
    return out


def server_cmd(suite_root: Path) -> "tuple[str, list[str]]":
    # The CLI, not an absolute path: configs stay valid when the suite moves, and
    # `design-suite mcp` locates the server through the one locator order.
    return "design-suite", ["mcp"]


def gemini_settings(current, suite_root: Path) -> str:
    data = _load_json(current)
    ctx = data.setdefault("context", {})
    if not isinstance(ctx, dict):
        raise Unparseable("context exists and is not an object")
    names = ctx.get("fileName")
    if names is None:
        names = ["AGENTS.md", "GEMINI.md"]      # keep Gemini's default alongside
    elif isinstance(names, str):
        names = [names] if names == "AGENTS.md" else ["AGENTS.md", names]
    elif isinstance(names, list):
        names = names if "AGENTS.md" in names else ["AGENTS.md", *names]
    else:
        raise Unparseable("context.fileName is neither a string nor a list")
    ctx["fileName"] = names
    cmd, args = server_cmd(suite_root)
    data.setdefault("mcpServers", {})[SERVER] = {"command": cmd, "args": args}
    if current is not None and _load_json(current) == data:
        return current
    return _dump(data)


def codex_toml(current, suite_root: Path) -> str:
    cmd, args = server_cmd(suite_root)
    block = (f"{BEGIN_TOML}\n[mcp_servers.{SERVER}]\ncommand = {json.dumps(cmd)}\n"
             f"args = {json.dumps(args)}\n{END_TOML}\n")
    if current is not None and BEGIN_TOML not in current and re.search(
            rf"^\s*\[mcp_servers\.\"?{re.escape(SERVER)}\"?\]", current, re.M):
        raise Unparseable(f"[mcp_servers.{SERVER}] is already declared outside the "
                          f"generated block — leaving the user's entry alone")
    return upsert_block(current, block, BEGIN_TOML, END_TOML)


# ----------------------------------------------------------------------- skills
FRONT = re.compile(r"\A---\n(.*?)\n---\n", re.S)


def parse_front(text: str) -> "tuple[dict, str]":
    m = FRONT.match(text)
    if not m:
        return {}, text
    meta = {}
    for line in m.group(1).splitlines():
        if ":" in line and not line.startswith((" ", "\t")):
            k, v = line.split(":", 1)
            meta[k.strip()] = v.strip()
    return meta, text[m.end():]


def rewrite_root(text: str) -> str:
    return (text.replace("${CLAUDE_PLUGIN_ROOT}", LOCATOR)
                .replace("$CLAUDE_PLUGIN_ROOT", LOCATOR))


def skill_text(src: Path) -> "str | None":
    meta, body = parse_front(src.read_text(encoding="utf-8"))
    name = meta.get("name", "").strip("'\"") or src.stem
    desc = meta.get("description")
    if not desc:
        return None
    explicit = meta.get("invocation", "").strip("'\"") == "explicit"
    front = [f"name: {name}", f"description: {desc}"]
    for k in ("invocation", "maturity"):
        if k in meta:
            front.append(f"{k}: {meta[k]}")
    pre = [SKILL_MARK.format(name=src.stem), "",
           "> **Locating scripts.** Paths below use `${DESIGN_SUITE_HOME}`, the suite "
           "root. If it is unset, run `export DESIGN_SUITE_HOME=\"$(design-suite where "
           "| cut -f1)\"` first.", ""]
    if explicit:
        pre += ["> **Explicit-tier.** Run this skill **only when the user directly asks "
                "for it**. Never invoke it on your own initiative, even if it looks "
                "relevant — it writes files or sets project conventions.", ""]
    return "---\n" + "\n".join(front) + "\n---\n" + "\n".join(pre) + rewrite_root(body)


# -------------------------------------------------------------------- shadowing
ZED_FIRST = (".rules", ".cursorrules", ".windsurfrules", ".clinerules",
             ".github/copilot-instructions.md", "AGENT.md", "AGENTS.md")


def wiring(project: Path) -> "list[tuple[str, str, str]]":
    """(harness, status, detail). status: WIRED / NOT WIRED / SHADOWED / UNKNOWN."""
    out = []
    agents = project / "AGENTS.md"
    has_block = agents.is_file() and BEGIN_MD in agents.read_text(encoding="utf-8", errors="replace")
    if not has_block:
        out.append(("all AGENTS.md readers", "NOT WIRED",
                    "AGENTS.md has no design-suite block — run `design-suite harness --apply`"))
    for rel in ("CLAUDE.md", ".claude/CLAUDE.md"):
        p = project / rel
        if p.is_file() and not re.search(r"^@AGENTS\.md\s*$", p.read_text(
                encoding="utf-8", errors="replace"), re.M):
            out.append(("Claude Code", "SHADOWED",
                        f"{rel} exists without an `@AGENTS.md` import line, so Claude "
                        f"Code reads it instead of AGENTS.md — add `@AGENTS.md` to it"))
    first = next((r for r in ZED_FIRST if (project / r).is_file()), None)
    if first and first != "AGENTS.md":
        out.append(("Zed", "SHADOWED",
                    f"{first} is read first and Zed reads only the first match — "
                    f"AGENTS.md is never seen by Zed"))
    if (project / "AGENTS.override.md").is_file():
        out.append(("Codex", "SHADOWED", "AGENTS.override.md takes precedence over AGENTS.md"))
    if agents.is_file() and agents.stat().st_size > CODEX_AGENTS_CAP:
        out.append(("Codex", "SHADOWED",
                    f"AGENTS.md is {agents.stat().st_size} bytes, over Codex's 32 KiB "
                    f"default cap; the tail (and possibly the block) is truncated"))
    gs = project / ".gemini" / "settings.json"
    try:
        names = (_load_json(gs.read_text()) if gs.is_file() else {}).get("context", {}).get("fileName")
        listed = names == "AGENTS.md" or (isinstance(names, list) and "AGENTS.md" in names)
        if not listed:
            out.append(("Gemini CLI", "NOT WIRED",
                        "context.fileName does not include AGENTS.md (default reads GEMINI.md only)"))
    except (Unparseable, AttributeError) as e:
        out.append(("Gemini CLI", "UNKNOWN", f".gemini/settings.json: {e}"))
    ac = project / ".aider.conf.yml"
    if not (ac.is_file() and re.search(r"AGENTS\.md", ac.read_text(errors="replace"))):
        out.append(("Aider", "NOT WIRED",
                    "no `read: AGENTS.md` in .aider.conf.yml (Aider has no auto-discovery)"))
    return out


# ------------------------------------------------------------------------- plan
def _read(p: Path) -> "str | None":
    return p.read_text(encoding="utf-8") if p.is_file() else None


def build_plan(project: Path, suite_root: Path, include_claude: bool = False) -> Plan:
    plan = Plan()
    cmd, args = server_cmd(suite_root)
    entry = {"command": cmd, "args": args}

    def target(rel: str, fn):
        cur = _read(project / rel)
        try:
            new = fn(cur)
        except Unparseable as e:
            plan.refusals.append((rel, str(e)))
            return
        if new is None or new == cur:
            plan.unchanged.append(rel)
        else:
            plan.writes[rel] = new

    block = agents_block(suite_root)
    target("AGENTS.md", lambda c: upsert_block(c, block, BEGIN_MD, END_MD))
    target(".gemini/settings.json", lambda c: gemini_settings(c, suite_root))
    target(".cursor/mcp.json", lambda c: json_set(c, ("mcpServers", SERVER), entry))
    target(".vscode/mcp.json", lambda c: json_set(c, ("servers", SERVER), {"type": "stdio", **entry}))
    if include_claude:
        target(".mcp.json", lambda c: json_set(c, ("mcpServers", SERVER), entry))
    target(".codex/config.toml", lambda c: codex_toml(c, suite_root))
    target("opencode.json", lambda c: json_set(c, ("mcp", SERVER),
                                               {"type": "local", "command": [cmd, *args]}))
    if (project / ".aider.conf.yml").is_file():
        if "AGENTS.md" not in _read(project / ".aider.conf.yml"):
            plan.instructions.append("Aider: add `read: AGENTS.md` to .aider.conf.yml "
                                     "(existing YAML is not rewritten)")
    else:
        target(".aider.conf.yml", lambda c: "read: AGENTS.md\n")

    for src in sorted((suite_root / "commands").glob("*.md")):
        text = skill_text(src)
        if text is None:
            continue
        for d in SKILL_DIRS + ((CLAUDE_SKILL_DIR,) if include_claude else ()):
            rel = f"{d}/{src.stem}/SKILL.md"
            cur = _read(project / rel)
            if cur is not None and SKILL_MARK.format(name=src.stem) not in cur:
                plan.refusals.append((rel, "exists and was not generated by the suite — not overwritten"))
            elif cur == text:
                plan.unchanged.append(rel)
            else:
                plan.writes[rel] = text

    py = " ".join([cmd, *args])
    for rel in ("CLAUDE.md", ".claude/CLAUDE.md"):
        c = _read(project / rel)
        if c is not None and not re.search(r"^@AGENTS\.md\s*$", c, re.M):
            plan.instructions.append(f"Claude Code: add a line `@AGENTS.md` to {rel} "
                                     f"(not edited — it is your file)")
    if not include_claude:
        plan.instructions.append(
            "Claude Code: .mcp.json and .claude/skills/ NOT generated — the Claude plugin "
            "already provides the MCP server and skills. Pass --include-claude to generate them "
            "(e.g. Claude Code without the plugin, or Cline/VS Code reading .claude/skills/)")
    if shutil.which("design-suite") is None:
        plan.warnings_pre = ["design-suite CLI is NOT on PATH: every generated MCP config runs "
                             "`design-suite mcp` and will fail to start until it is installed "
                             "(pipx install / uv tool install)"]
    plan.instructions += [
        f"Zed: add to .zed/settings.json under `context_servers` a server named "
        f"`{SERVER}` running `{py}` (entry shape not given in the research doc — not written)",
        f"Devin Desktop: user-level only — add `{SERVER}` running `{py}` to "
        f"~/.config/devin/mcp_config.json yourself (never written: outside the project)",
        f"Cline: user-level only — add `{SERVER}` running `{py}` to "
        f"cline_mcp_settings.json via Cline's MCP settings (never written)",
        "Copilot cloud agent: MCP is configured in the repository Settings UI (tools "
        "allowlist required) — not a file this can write",
    ]
    plan.warnings = plan.warnings_pre + [f"{h}: {s} — {d}" for h, s, d in wiring_after(project, plan)]
    return plan


def wiring_after(project: Path, plan: Plan):
    """Shadowing that survives the apply: AGENTS.md/Gemini/Aider are fixed by it."""
    fixed = {"all AGENTS.md readers"}
    if ".gemini/settings.json" in plan.writes or ".gemini/settings.json" in plan.unchanged:
        fixed.add("Gemini CLI")
    if ".aider.conf.yml" in plan.writes or ".aider.conf.yml" in plan.unchanged:
        fixed.add("Aider")
    return [w for w in wiring(project) if w[0] not in fixed]
